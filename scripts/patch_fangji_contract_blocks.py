FOUR = ["MOTTO", "PROBLEM", "环境逼迫", "知识积累"]


def main():
    done = []
    for slug, (problem, env, know) in BLOCKS.items():
        p = os.path.join(CH, slug, "docs", "zh.md")
        s = io.open(p, encoding="utf-8").read()
        if "PROBLEM" in s and "环境逼迫" in s:
            continue
        lines = s.split("\n")
        # 找 MOTTO 行
        idx = next((i for i, l in enumerate(lines) if "MOTTO" in l), None)
        if idx is None:
            print(f"[warn] {slug} 没有 MOTTO 行，跳过")
            continue
        block = [
            "",
            f"> **PROBLEM:** {problem}",
            "",
            f"> **双根因定位:** {env} + {know}",
            "",
            f"> 本章的边界声明：只讲教材怎么规定方与法的关系，{('不构成临床处方依据') if slug.startswith('0') else '不构成诊断或用药依据'}；所有数字由 `standards/fangji` 现算，抽不出的结构如实留空。",
        ]
        lines[idx + 1:idx + 1] = block
        io.open(p, "w", encoding="utf-8").write("\n".join(lines))
        done.append(slug)

    print(f"补块 {len(done)} 章：{', '.join(done)}")

    # 校验四关键词
    for slug in BLOCKS:
        s = io.open(os.path.join(CH, slug, "docs", "zh.md"), encoding="utf-8").read()
        missing = [k for k in FOUR if k not in s]
        has_edge = bool(re.search(r"丢掉了什么|丢失|边界声明|不构成", s))
        print(f"  {slug}: 缺={missing or '无'} 边界={has_edge}")


if __name__ == "__main__":
    main()
