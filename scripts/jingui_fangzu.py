# ── 生成归属表（供 scripts/build_jingui_fangzu.js 读；两边同一份事实来源）────────────
def emit(root: str) -> int:
    import io as _io
    import json as _json
    import os as _os
    import sys as _sys

    ben = _json.load(_io.open(_os.path.join(root, "standards", "jingui", "底本.json"), encoding="utf-8"))
    all_names = {f["nameSimp"].replace("方", "") for p in ben["pian"]
                 for a in (p.get("articles") or []) for f in (a.get("formulas") or [])}
    seen = {}
    for fam, gong, members in FAMILIES:
        for m in members:
            seen.setdefault(m, []).append(fam)
    dup = {k: v for k, v in seen.items() if len(v) > 1}
    miss = sorted(all_names - set(seen))
    extra = sorted(set(seen) - all_names)
    print("族 %d · 归一属 %d / 底本唯一方名 %d" % (len(FAMILIES), len(seen), len(all_names)))
    if dup:
        print("✗ 重复归属：%s" % dup)
    if miss:
        print("✗ 未归属：%s" % miss)
    if extra:
        print("✗ 不存在的方名：%s" % extra)
    if dup or miss or extra:
        return 1
    out = [{"family": f, "gong": g, "members": m} for f, g, m in FAMILIES]
    path = _os.path.join(root, "standards", "jingui", "fangzu-map.json")
    text = _json.dumps({"source": "scripts/jingui_fangzu.py", "families": out},
                       ensure_ascii=False, indent=1) + NL
    _io.open(path, "w", encoding="utf-8", newline=NL).write(text)
    print("✓ → %s" % path)
    return 0


if __name__ == "__main__":
    import os as _os
    import sys as _sys
    _ROOT = _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__)))
    raise _sys.exit(emit(_ROOT))
