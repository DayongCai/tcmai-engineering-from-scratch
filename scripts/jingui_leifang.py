def emit(root: str) -> int:
    import io
    import json
    import os

    out = [{"a": a, "b": b, "text": t} for (a, b), t in LEIFANG.items()]
    path = os.path.join(root, "standards", "jingui", "leifang-map.json")
    text = json.dumps({"source": "scripts/jingui_leifang.py", "pairs": out},
                      ensure_ascii=False, indent=1) + NL
    io.open(path, "w", encoding="utf-8", newline=NL).write(text)
    print("✓ 类方鉴别 %d 对 → %s" % (len(out), path))
    return 0


