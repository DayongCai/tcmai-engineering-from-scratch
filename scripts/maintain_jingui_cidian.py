def main() -> int:
    src = io.open(PATH, encoding="utf-8").read()
    lines = src.split(NL)
    # 注意括号：裸 `\("A|B",` 里的是「整串前缀」的择一，会把只匹配到第一条——第一版就这么只删了 1 条
    drop_re = re.compile(r'^\s*\("(?:%s)",' % "|".join(re.escape(w) for w in DROP))
    kept, removed = [], []
    for ln in lines:
        if drop_re.match(ln):
            removed.append(ln.strip()[:24])
            continue
        kept.append(ln)
    # 补遗：插在 CIDIAN 列表的收尾 "]" 之前
    block = []
    new = [(w, g) for w, g in ADD if ('("%s",' % w) not in src]  # 幂等：已补过的不再补
    if new:
        block.append("    # ── 补遗：覆盖原先无词可解的条文（2026-11-11）──────────────────────────")
        block += ['    ("%s", "%s"),' % (w, g) for w, g in new]
    out, done = [], False
    for ln in kept:
        if not done and ln.strip() == "]":
            out.extend(block)
            done = True
        out.append(ln)
    io.open(PATH, "w", encoding="utf-8", newline=NL).write(NL.join(out))
    print("删去 %d 条（全库不出现）· 补遗 %d 条 → %s" % (len(removed), len(ADD), PATH))
    for r in removed:
        print("   -", r)
    return 0


if __name__ == "__main__":
    sys.exit(main())
