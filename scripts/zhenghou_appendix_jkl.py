# -*- coding: utf-8 -*-
"""scripts/zhenghou_appendix_jkl.py —— 教材附录 J / K / L 的渲染器

三块补篇层（证象学 / 危候判据 / 证—法—方）在课程里是第 25–27 章，在教材里落成三个附录：
J 证象学总表 · K 危候判据表 · L 证—法—方索引。

数据源：`standards/zhenghou-cidian/{证象学,危候判据,方症索引,危候判据-复核}.json`
（由 `scripts/build_zhenghou_sanji_supplement.py` 与 `scripts/verify_weihou_pages.py` 生成）。
本模块只排版，不重算、不补数；缺文件直接抛错，不写占位符。
"""
import io
import json
import os

STD = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "standards", "zhenghou-cidian")


def _load(name):
    p = os.path.join(STD, name)
    if not os.path.exists(p):
        raise SystemExit("缺 %s —— 先跑 build_zhenghou_sanji_supplement.py / verify_weihou_pages.py" % name)
    return json.load(io.open(p, encoding="utf-8"))


def render_j():
    z = _load("证象学.json")
    L = []
    A = L.append
    A("# 附录 J · 证象学总表")
    A("")
    A("> 证象是《中医证候学》最小的识别单位。这本辞典的每一条候都由若干证象组成，"
      "而证象又由「位」与「病机」两个零件拼出来 —— 本附录把这三个层级一次列清。")
    A("")
    A("## J.1 定义与规模")
    A("")
    A("| 项 | 值 | 来源 |")
    A("|---|---|---|")
    A("| 定义 | 反映单一病机状态的识别单位（单位病机），不是独立证候 | 概论·第四节 |")
    A("| 组成 | 症象 + 脉象 + 舌象，按病机形态归并 | 概论·第四节 |")
    A("| 效价 | 各表象同等效价：「但见一症便是，不必悉具」 | 概论·第四节 |")
    A("| 病机（行） | %d | 附录一 |" % z["格"]["行（病机）"])
    A("| 位（列） | %d | 附录一 |" % z["格"]["列（位）"])
    A("| 合法格 | **%d**（书内声明 %d，差 %d） | 附录一逐格读表 |" % (
        z["格"]["合法格"], z["格"]["书内声明"], z["格"]["差异"]))
    A("| 态 | %d 个，分 %d 族 | 语素-态 |" % (z["态"]["总"], len(z["态"]["族"])))
    A("")
    A("## J.2 位 × 病机：%d 个合法格" % z["格"]["合法格"])
    A("")
    A("行是病机，列是位，格内是原书印着的证象名。**空格是合法缺席**（原书没有这一组合），不是缺失。")
    A("")
    cols = z["格"]["列表"]
    A("| 病机 \\ 位 | " + " | ".join(cols) + " |")
    A("|---" * (len(cols) + 1) + "|")
    grid = {}
    for c in z["格"]["格"]:
        grid[(c["病机"], c["位"])] = c["证象"]
    for row in z["格"]["行表"]:
        A("| **" + row + "** | " + " | ".join(grid.get((row, col), "·") for col in cols) + " |")
    A("")
    A("## J.3 态表：%d 态 / %d 族" % (z["态"]["总"], len(z["态"]["族"])))
    A("")
    A("| 族 | 态数 |")
    A("|---|--:|")
    for k, v in z["态"]["族"].items():
        A("| %s | %d |" % (k, v))
    A("")
    A("态的完整释义见 `语素-态.json`；本附录只给族与计数 —— 108 条释义搬进来会把书撑成字典。")
    A("")
    A("## J.4 【证象组合】的形态普查")
    A("")
    c = z["组合形态"]
    A("| 项 | 数 |")
    A("|---|--:|")
    A("| 候总数 | %d |" % c["候总数"])
    A("| 有【证象组合】字段 | %d |" % c["有证象组合字段"])
    for k, v in c["字段形态"].items():
        A("| %s | %d |" % (k, v))
    A("| 标签种类 | %d |" % c["标签种类"])
    A("| 标签出现总次 | %d |" % c["标签出现总次"])
    A("")
    A("标签型按「位缩写 + 态根」拆开逐个判：")
    A("")
    A("| 判定 | 次数 |")
    A("|---|--:|")
    for k, v in c["标签型判定"].items():
        A("| %s | %d |" % (k, v))
    A("")
    A("**可解释率 = %d / %d = %.1f%%**。这个数不高，但它是诚实的：拆得开的才算拆开。"
      % (c["标签型判定"].get("可解释（位在附录一 + 态根映得回病机）", 0), c["标签出现总次"],
         c["可解释率"] * 100))
    A("")
    A("## J.5 读法四条")
    A("")
    for x in z["读法"]:
        A("- " + x)
    A("")
    A("## J.6 校勘")
    A("")
    for x in z["校勘"]:
        A("- " + x)
    A("")
    A("---")
    A("")
    A("**边界**：本附录不给证象的临床权重，也不判断某条证象在具体病人身上是否成立。"
      "空格不等于缺失，可解释率不等于覆盖率。")
    A("")
    return "\n".join(L)


def render_k():
    w = _load("危候判据.json")
    r = _load("危候判据-复核.json")
    L = []
    A = L.append
    A("# 附录 K · 危候判据表")
    A("")
    A("> **这是词面判据，不是临床判据。** 它回答「这一候的名字与治法里有没有危象语义」，"
      "不回答「这个病人现在危不危险」。")
    A("")
    A("## K.1 三档与判据词")
    A("")
    A("| 档 | 候名态根 |")
    A("|---|---|")
    for t, roots in w["口径"]["三档"].items():
        A("| %s | %s |" % (t, "、".join(roots)))
    A("")
    A("治则提示词（作佐证，不单独定档）：%s。" % "、".join(w["口径"]["治则提示词"]))
    A("")
    A("## K.2 百姓说法入口（%d 条）" % len(w["口语入口"]))
    A("")
    A("| 说法 | 归到 |")
    A("|---|---|")
    for k, v in w["口语入口"].items():
        A("| %s | %s |" % (k, v))
    A("")
    A("## K.3 候级清单（%d 条）" % w["counts"]["命中"])
    A("")
    A("| 全码 | 候名 | 档 | 依据 | 印张 |")
    A("|---|---|---|---|--:|")
    for h in w["清单"]:
        if h["tier"] == "候选":
            continue
        A("| `%s` | %s | %s | %s | %s |" % (h["code"], h["name"], h["tier"], h["why"], h["printed"]))
    A("")
    A("另有 **%d 条「候选」**：候名里没有危候态根，只有治则用语命中。它们不进上表，"
      "单列在 `危候判据.json` 的 `清单` 里（tier=候选），由人工复核 —— 只靠治法词会把普通候算成危候。"
      % w["counts"]["按档"].get("候选", 0))
    A("")
    A("## K.4 原页复核（%d 条逐条回印张页）" % r["counts"]["复核条数"])
    A("")
    A("| 项 | 结果 |")
    A("|---|--:|")
    A("| 候名在印张页命中 | %d / %d |" % (r["counts"]["复核条数"], r["counts"]["复核条数"]))
    for k, v in r["counts"]["分档"].items():
        A("| %s | %d |" % (k, v))
    A("| 按册（上/中/下） | %s |" % " · ".join("%s %d" % (a, b) for a, b in r["counts"]["按册"].items()))
    A("| 目录页可交叉核 | %d 条，对齐 %d、偏差 %d |" % (
        r["counts"]["目录页可校"], r["counts"]["目录页对齐"], r["counts"]["目录页偏差"]))
    A("")
    A("**能说与不能说**：可以说「%d 条候名都在原书印张页出现」；不能说「%d 条全链核过」——"
      "中、下两册的目录书签目标页在扫描件里已失效，那部分只有候名一条轴。"
      % (r["counts"]["复核条数"], r["counts"]["复核条数"]))
    A("")
    A("## K.5 校勘")
    A("")
    for x in w["校勘"] + r["校勘"]:
        A("- " + x)
    A("")
    A("---")
    A("")
    A("**边界**：本附录不做生死判断、不给处置时限、不给急救流程；急诊处置按机构规范。"
      "危候清单仅供检索与教学复核，删条必须写理由。")
    A("")
    return "\n".join(L)


def render_l():
    f = _load("方症索引.json")
    L = []
    A = L.append
    A("# 附录 L · 证—法—方索引")
    A("")
    A("> 一候一条：候是索引键，法是该候【治则】的首句，方是该候【方症】里印着的方名。"
      "**这是对接关系，不是处方。**")
    A("")
    A("## L.1 覆盖")
    A("")
    A("| 项 | 数 | 占比 |")
    A("|---|--:|--:|")
    A("| 有【方症】字段 | %d | %.1f%% |" % (f["counts"]["有方症字段"], f["counts"]["有方症字段"] / 1864 * 100))
    A("| 取到方名 | **%d** | %.1f%% |" % (f["counts"]["取到方名"], f["counts"]["取到方名"] / 1864 * 100))
    A("| 取不到（记 null，不硬造） | %d | %.1f%% |" % (
        f["counts"]["取不到"], f["counts"]["取不到"] / 1864 * 100))
    A("| 含多首方（一候多方） | %d | %.1f%% |" % (f["counts"]["含多首方"], f["counts"]["含多首方"] / 1864 * 100))
    A("| 方名种类 | %d | — |" % f["counts"]["方名种类"])
    A("")
    A("## L.2 方名频次前 20")
    A("")
    A("| 方名 | 出现候数 |")
    A("|---|--:|")
    for name, n in f["方名频次Top20"]:
        A("| %s | %d |" % (name, n))
    A("")
    A("频次说明的是「哪些方被反复当作某类候的落点」，不是「这些方最好」或「最常用」。")
    A("")
    A("## L.3 抽样（每门 3 条，共 36 条）")
    A("")
    A("| 全码 | 候名 | 法（治则首句） | 方 | 印张 |")
    A("|---|---|---|---|--:|")
    seen = {}
    for r in f["条目"]:
        seen.setdefault(r["men"], 0)
        if seen[r["men"]] >= 3:
            continue
        seen[r["men"]] += 1
        A("| `%s` | %s | %s | %s | %s |" % (
            r["code"], r["name"], (r["治法首句"] or "—")[:46], r["方名"] or "—（取不到）", r["printed"]))
    A("")
    A("全表 %d 条在 `方症索引.json`，可用 `node scripts/zhenghou_query.js` 按候名或全码查。" % len(f["条目"]))
    A("")
    A("## L.4 校勘")
    A("")
    for x in f["校勘"]:
        A("- " + x)
    A("")
    A("---")
    A("")
    A("**边界**：本附录不给剂量、煎服法、加减与疗程；不替代《方剂学》的主治归经，也不构成用药建议。"
      "处方由具备资质者依规范开具。")
    A("")
    return "\n".join(L)
